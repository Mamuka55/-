async function ingest(base, body) {
  const { __token, ...payload } = body;
  const res = await fetch(`${base}/api/kb/ingest`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', 'X-Epic-Client': 'cli', Cookie: `epic_ai_session=${__token}` },
    body: JSON.stringify(payload),
  });
  const text = await res.text();
  let json; try { json = JSON.parse(text); } catch { json = { raw: text.slice(0, 300) }; }
  if (!res.ok) throw new Error(`ingest failed (${res.status}) for thread ${payload.threadId}: ${JSON.stringify(json).slice(0, 400)}`);
  return json;
}

